export type GotchaLogItem = {
  turnIndex: number;
  timestamp: number;
  question: string;
  chosen: string;
  freeText: boolean;
  retracted?: boolean;
};

export function buildGotchaContext(
  log: GotchaLogItem[],
  trimmed: boolean,
): string {
  const head =
    log.length === 0
      ? "## 言質ログ\n(まだユーザーの言質は記録されていない。最初の発言を取る好機である。)"
      : [
          "## 言質ログ(ユーザーの過去発言。武器として使ってよい)",
          ...log.map((e) => {
            const kind = e.freeText ? "自由記述" : "選択";
            const tag = e.retracted ? " [撤回済]" : "";
            return `- T${e.turnIndex + 1} [${kind}]${tag} 問: 「${e.question}」 → 答: 「${e.chosen}」`;
          }),
          "",
          "上記はユーザー自身の言葉である。矛盾や含意の抽出に用いよ。原文の改変は禁止。",
          "[撤回済] のついた言質は、もはや矛盾の指摘材料として使ってはならない。ただし「人は前言を撤回する。撤回後に残るものは何か」という新たな問いの種にはしてよい。",
        ].join("\n");

  if (!trimmed) return head;
  return [
    head,
    "",
    "## 注記",
    "対話履歴は長いため、直近の往復のみが messages として渡されている。古い往復の要点はこの言質ログにある。古いAI応答の正確な文言を引用してはならない。",
  ].join("\n");
}

